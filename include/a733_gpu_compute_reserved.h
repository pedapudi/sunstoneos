#ifndef SUNSTONE_A733_GPU_COMPUTE_RESERVED_H
#define SUNSTONE_A733_GPU_COMPUTE_RESERVED_H
#include "a733_gpu_reserved.h"
#include "pvr_compute_service.h"
#include "pvr_compute_context.h"

#define A733_GPU_COMPUTE_PAYLOAD_PAGES 88u
struct a733_gpu_compute_reserved;
struct a733_gpu_compute_binding {
    uintptr_t self;
    struct a733_gpu_compute_reserved *session;
    struct a733_gpu_reserved *firmware;
    struct pvr_gpu_service *service;
    struct device_memory_pool *wb, *nc;
    uint64_t owner;
};
/* Private static image storage. Zero once; serialize construction and every
 * pool operation. Binding, page lists, descriptors and generated bytes remain
 * immutable except for fields expressly owned by the existing compute service.
 * Copying/rebinding is forbidden. Self checks detect accidental copies; these
 * shared mappings do not protect against arbitrary privileged memory writes. */
struct a733_gpu_compute_reserved {
    struct a733_gpu_compute_binding binding;
    struct device_memory_lease payload_lease, firmware_lease, table_lease;
    struct device_memory_extent payload_extent, firmware_extent, table_extent;
    struct pvr_compute_service compute;
    struct pvr_compute_service_config config;
    struct pvr_compute_program_config programs;
    struct pvr_compute_program_result program_result;
    struct pvr_compute_job_config job;
    struct pvr_compute_job_image image;
    struct a733_gpu_vm_memory vm;
    struct pvr_gpu_vm_requirements requirements;
    struct pvr_mips_object mappings[PVR_FW_RESOURCE_COUNT + PVR_COMPUTE_SERVICE_OBJECTS];
    struct pvr_mips_boot boot;
    struct pvr_gpu_mapping maps[A733_GPU_COMPUTE_PAYLOAD_PAGES];
    uint64_t payload_pages[A733_GPU_COMPUTE_PAYLOAD_PAGES];
    uint64_t firmware_pages[PVR_COMPUTE_SERVICE_OBJECTS];
    uint64_t table_pages[PVR_COMPUTE_SERVICE_TABLE_PAGES];
    unsigned stage;
};

/* Native identity image, pre-scheduler, stopped/unattached private firmware.
 * Compose the actual fixed single-core preparation profile with the reserved
 * firmware instance and an uninitialized service. A nonzero 32-bit owner also
 * identifies the sole context. Allocate complete payload, NC firmware and
 * planner-sized WB table parents; retain all acquired parents on failure.
 * One fixed compute context owns the firmware address ranges for the entire
 * boot, including admitted failure. Success builds VM/program/context/job bytes,
 * extends the offline MIPS tables, and binds the existing
 * compute service. No physical completion, power, core-mode, isolation or drain
 * provider is supplied. Those remain independent runtime prerequisites.
 *
 * Local admission checks actual lease generations/extents, every CPU mapping,
 * generated map/descriptor correspondence and this constructor's retained build
 * provenance. External users/aliases remain excluded by the boot-pool contract.
 * No release, reset, free-list allocation, MMIO or cache publication occurs.
 * Returns the bound compute service, or NULL. Failed construction cannot retry.
 */
struct pvr_compute_service *a733_gpu_compute_reserved_prepare(
    struct a733_gpu_compute_reserved *, struct a733_gpu_reserved *,
    struct pvr_gpu_service *, uint32_t owner);
#endif
