#ifndef SUNSTONE_A733_G2D_APPLICATION_H
#define SUNSTONE_A733_G2D_APPLICATION_H
#include "a733_board_application.h"
#define A733_G2D_CONTRACT_MAGIC UINT64_C(0x4153373347324331)
#define A733_G2D_SESSION_MAGIC UINT64_C(0x4153373347324131)
#define A733_G2D_INPUT_CAPACITY 3686400u
#define A733_G2D_OUTPUT_CAPACITY 3686400u
#define A733_G2D_RESULT_BYTES 192u
#define A733_G2D_MAX_WIDTH 1280u
#define A733_G2D_MAX_HEIGHT 720u
#define A733_G2D_SESSION_SECONDS 20u
/* Pinned sunxi-g2d.h codes for the eight 32-bit RGB orders, 0 through 7. */
#define A733_G2D_FORMAT_ARGB8888 0u
#define A733_G2D_FORMAT_BGRX8888 7u
#define A733_G2D_FILL 1u
#define A733_G2D_BLIT 2u
#define A733_G2D_SRCOVER_SOLID 3u
#define A733_G2D_SCALE2X 4u
#define A733_G2D_SCALE 5u
#define A733_G2D_SRCOVER_IMAGE 6u
/* One retained fill, source-copy, source-over-solid, 2x enlargement, general
 * scaling or image-over-image operation. ARGB8888 uses little-endian B,G,R,A
 * bytes. The input digest covers stride*height bytes, including padding.
 * Output starts at zero; only the selected destination rectangle is modified.
 * Source-over uses straight per-pixel source alpha and an opaque color background.
 * Scale2x uses even destination w/h and a source crop of w/2 by h/2.
 * General scaling reads an sw by sh crop at sx,sy for any other destination
 * size, enlarging or reducing. Copy and general scaling may convert between
 * the eight 32-bit RGB orders: format describes the source and output_format
 * the destination. Image-over-image blends a w by h foreground at sx,sy, with
 * per-pixel alpha times plane alpha, over a w by h background at bx,by of the
 * same upload, keeping the background's own per-pixel alpha. Every extension
 * word an operation does not use, and reserved, must be zero.
 * Evidence fields bind reviewed physical facts, not observations inferred from
 * idle registers or generated by startup. */
struct a733_g2d_session {
    struct a733_board_session board;
    uint64_t magic,version,bytes,owner,authority,pck_client;
    uint8_t initial[32],memory[32],electrical[32],supervision[32];
    uint8_t fixture[32];
    uint32_t sw,sh,bx,by,alpha,output_format,reserved[2];
    uint32_t module,module_hz,iommu_gates[2],supply_uv,supply_rail;
    uint32_t width,height,stride,format,op,dx,dy,w,h,sx,sy,color;
};
_Static_assert(sizeof(struct a733_g2d_session)==904,"G2D immutable wire layout");
/* Nonzero w by h at x,y lies within width by height. Subtraction avoids
 * overflow, and w-1 wraps to the maximum for zero, so one compare checks both. */
static inline int a733_g2d_inside(uint32_t x,uint32_t y,uint32_t w,uint32_t h,uint32_t width,uint32_t height)
{return x<width&&y<height&&w-1u<width-x&&h-1u<height-y;}
/* The width, height and stride limits alone bound stride*height. */
_Static_assert((uint64_t)A733_G2D_MAX_WIDTH*4*A733_G2D_MAX_HEIGHT<=A733_G2D_INPUT_CAPACITY,
    "G2D geometry limits fit the source capacity");
static inline int a733_g2d_geometry_valid(const volatile struct a733_g2d_session *s)
{
    if(!s)return 0;
    /* One read of each word keeps the SRAM launcher's copy of this check small. */
    uint32_t width=s->width,height=s->height,stride=s->stride,op=s->op,w=s->w,h=s->h;
    uint32_t color=s->color,sw=s->sw,sh=s->sh,alpha=s->alpha;
    /* Words an operation does not use must be zero; only copy and general
     * scaling convert formats. */
    uint32_t scale=sw|sh,background=s->bx|s->by|alpha,formats=s->format|s->output_format;
    if(width>A733_G2D_MAX_WIDTH||height>A733_G2D_MAX_HEIGHT||
       stride<width*4||stride>A733_G2D_MAX_WIDTH*4||(stride&3)||
       formats>A733_G2D_FORMAT_BGRX8888||(s->reserved[0]|s->reserved[1])||
       !a733_g2d_inside(s->dx,s->dy,w,h,width,height)||
       (op!=A733_G2D_SCALE&&scale)||(op!=A733_G2D_SRCOVER_IMAGE&&background)||
       (op!=A733_G2D_BLIT&&op!=A733_G2D_SCALE&&formats))return 0;
    if(op==A733_G2D_FILL)return !(s->sx|s->sy);
    if(op==A733_G2D_SCALE2X){if((w|h)&1)return 0;sw=w/2;sh=h/2;}
    /* An identical-size scale is a copy, which leaves the scaler disabled. */
    else if(op==A733_G2D_SCALE){if(sw==w&&sh==h)return 0;}
    else if(op==A733_G2D_SRCOVER_SOLID){if((color>>24)!=255)return 0;color=0;sw=w;sh=h;}
    else if(op==A733_G2D_BLIT||op==A733_G2D_SRCOVER_IMAGE){sw=w;sh=h;}
    else return 0;
    return !color&&(op!=A733_G2D_SRCOVER_IMAGE||(alpha&&alpha<=255&&
        a733_g2d_inside(s->bx,s->by,w,h,width,height)))&&
        a733_g2d_inside(s->sx,s->sy,sw,sh,width,height);
}
int a733_g2d_session_valid(const struct a733_g2d_session *);
#endif
