uint32_t a733_pin_bank_mask(unsigned bank)
{
    static const uint8_t counts[A733_PIN_BANKS]={0,11,17,24,16,7,15,20,17,28,26,14,6};
    return bank<A733_PIN_BANKS && counts[bank] ? (UINT32_C(1)<<counts[bank])-1 : 0;
}
const struct a733_pin_descriptor *a733_pin_descriptor(unsigned bank, unsigned pin)
{
    return pin<32 && (a733_pin_bank_mask(bank)&(UINT32_C(1)<<pin)) ? &descriptors[bank][pin] : 0;
}
int a733_pin_config_valid_banked(unsigned bank,unsigned pin,struct a733_pin_config c)
{
    const struct a733_pin_descriptor *d=a733_pin_descriptor(bank,pin);
    return d && c.function<16 && (d->functions&(1u<<c.function)) && c.pull<=2 && c.drive<=3;
}
int a733_pin_fields_banked(unsigned bank,unsigned pin,struct a733_pin_fields *out)
{
    if (!out || !a733_pin_descriptor(bank,pin)) return 0;
    uintptr_t base=bank<A733_PIN_L ? A733_PINS_BASE+0x80+bank*0x80 : A733_PINS_R_BASE+(bank-A733_PIN_L)*0x30;
    unsigned drive=bank<A733_PIN_L ? 0x20 : 0x14;
    unsigned pull=bank<A733_PIN_L ? 0x30 : 0x24;
    *out=(struct a733_pin_fields){base+(pin/8)*4,base+pull+(pin/16)*4,
        base+drive+(pin/8)*4,(pin%8)*4,(pin%16)*2,(pin%8)*4};
    return 1;
}
