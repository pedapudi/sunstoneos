        ppp[1]=(ppp[1]&~(1u<<21))|((s&PVR_RENDER_BATCH_NO_COLOR)?1u<<21:0);
        ppp[2]=(ppp[2]&~((7u<<24)|(1u<<21)|(7u<<17)|255u)) | (blend?1u<<24:0) |
            ((s&PVR_RENDER_BATCH_DEPTH_WRITE)?0:1u<<21) | (s&7u)<<17 |
            ((s&PVR_RENDER_BATCH_STENCIL)?b[i].stencil&255u:0);
        if(s&PVR_RENDER_BATCH_STENCIL)
            ppp[3]=((s>>11)&7u)<<25 | ((s>>14)&7u)<<22 | ((s>>17)&7u)<<19 | ((s>>20)&7u)<<16 |
                ((b[i].stencil>>8)&255u)<<8 | ((b[i].stencil>>16)&255u);
