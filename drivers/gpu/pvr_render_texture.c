    if(profile<2 || profile>PVR_RENDER_BATCH_PROFILE || !payload || bytes!=PVR_RENDER_PROGRAM_BYTES || !image ||
        !pvr_render_texture_geometry(width,height,&stride,&output) ||
        !pvr_render_programs_build(payload,bytes,image))return 0;
