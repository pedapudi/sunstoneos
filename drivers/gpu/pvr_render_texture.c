    if(!payload || !batches || !pvr_render_batch_frame_valid(frame) || !width || !height ||
        width>PVR_RENDER_TEXTURE_MAX_WIDTH || height>PVR_RENDER_TEXTURE_MAX_HEIGHT)return 0;
