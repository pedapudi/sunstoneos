int pvr_render_draw_programs_build(void *payload,size_t bytes)
{
    if(!payload || bytes!=PVR_RENDER_PROGRAM_BYTES || (uintptr_t)payload>UINTPTR_MAX-bytes)return 0;
    memcpy((unsigned char *)payload+1792,draw_pds,sizeof(draw_pds));
    memcpy((unsigned char *)payload+6400,draw_usc,sizeof(draw_usc));
    memcpy((unsigned char *)payload+69632,draw_vdm,sizeof(draw_vdm));
    memcpy((unsigned char *)payload+69888,draw_ppp,sizeof(draw_ppp));
    memcpy((unsigned char *)payload+73792,draw_meta,sizeof(draw_meta));
    memcpy((unsigned char *)payload+73824,draw_scissor,sizeof(draw_scissor));
    return 1;
}
int pvr_render_draw_vertices_valid(const void *data,size_t bytes,uint32_t count)
{
    if(!data || count<3 || count>PVR_RENDER_DRAW_VERTICES || count%3 ||
        bytes!=(size_t)count*sizeof(struct pvr_render_vertex) || (uintptr_t)data>UINTPTR_MAX-bytes)return 0;
    for(uint32_t v=0;v<count;++v) {
        uint32_t words[8];memcpy(words,(const unsigned char *)data+v*32,32);
        if((words[0]&0x7fffffff)>0x3f800000 || (words[1]&0x7fffffff)>0x3f800000 ||
            (words[2]&0x7fffffff) || words[3]!=0x3f800000)return 0;
        for(unsigned i=4;i<8;++i)
            if((words[i]&0x7fffffff)>0x3f800000 || ((words[i]&0x80000000) && (words[i]&0x7fffffff)))return 0;
    }
    return 1;
}
