#!/usr/bin/env python3
"""Write the catalogue of reviewed stream-processor programs (drivers/npu/nbg_sp_programs.inc).

For each stream-processor operation (kind 6) of the given graphs, the program body is the pair count and every
0x08010e5c and 0x08010e5d operand as little-endian 32-bit words; the catalogue holds the SHA-256 of that body, so the
repository holds no instruction words. The loader (drivers/npu/nbg_assembly.c) refuses a program that is not listed.
Review a graph before adding its programs: the meaning of the words is not interpreted
(docs/hardware/npu-command-formats.md).

  npu-sp-programs.py --native LIB --output FILE GRAPH.nb ...

LIB is a shared library of the OS decoder (tools/npu-nbg-census.py builds one).
"""
import argparse, ctypes as c, hashlib, importlib.util, struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('nbg_model', ROOT / 'checks/nbg-model.py')
nm = importlib.util.module_from_spec(spec); spec.loader.exec_module(nm)


def programs(native, path):
    graph = nm.Native(native, path.read_bytes())
    for operation in graph.operations():
        if operation[0] != 6:
            continue
        span = nm.Span()
        assert graph.lib.nbg_model_table(c.byref(graph.view), 26, operation[3], c.byref(span)) == 1
        words = struct.unpack('<%dI' % (span.bytes // 4), c.string_at(span.data, span.bytes))
        pairs = (len(words) * 4 - 40) // 16
        body = struct.pack('<I', pairs) + b''.join(struct.pack('<II', words[3 + 4 * i], words[5 + 4 * i]) for i in range(pairs))
        yield hashlib.sha256(body).digest()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--native', type=Path, required=True)
    ap.add_argument('--output', type=Path, required=True)
    ap.add_argument('graphs', nargs='+', type=Path)
    a = ap.parse_args()
    seen = sorted({digest for graph in a.graphs for digest in programs(a.native, graph)})
    lines = ['/* Generated by tools/npu-sp-programs.py: SHA-256 of each reviewed stream-processor program body. */']
    for digest in seen:
        lines.append('{' + ','.join('0x%02x' % b for b in digest) + '},')
    a.output.write_text('\n'.join(lines) + '\n')
    print(len(seen), 'programs')


if __name__ == '__main__':
    main()
