#!/usr/bin/env python3
"""Generate the G2D mixer's YUV-to-RGB tables from the BT.601 and BT.709 matrices.

The mixer's colour-space converter computes each output channel as (cy * Y + cu * U + cv * V + k) >> 10, clamped to 0
to 255 (docs/g2d-os.md#camera-frame-conversion). Each coefficient is a signed 13-bit field and each constant a signed
20-bit field (g2d_mixer_type.h, union g2d_mixer_bld_cs_coeff and union g2d_mixer_bld_cs_const). The tables here replace
the vendor's Ycbcr2rgb_601 and Ycbcr2rgb_709 blocks (g2d_bld.c 37-50 and 66-79).

The matrices. With luma weights Kr and Kb and Kg = 1 - Kr - Kb, the non-linear signals E'R, E'G and E'B follow from E'Y,
E'PB and E'PR as
  E'R = E'Y + 2 (1 - Kr) E'PR
  E'G = E'Y - 2 Kb (1 - Kb) / Kg E'PB - 2 Kr (1 - Kr) / Kg E'PR
  E'B = E'Y + 2 (1 - Kb) E'PB
which inverts the luma and colour-difference equations of ITU-R BT.601-7 (section 2.5.1 to 2.5.3, Kr 0.299, Kb 0.114)
and ITU-R BT.709-6 (items 3.2 and 3.3, Kr 0.2126, Kb 0.0722). The 8-bit codes are
  - limited range (BT.601-7 section 2.5.3, BT.709-6 item 4.6): Y = 219 E'Y + 16, U = 224 E'PB + 128, V = 224 E'PR + 128;
  - full range (ITU-T H.273, VideoFullRangeFlag 1): Y = 255 E'Y, U = 255 E'PB + 128, V = 255 E'PR + 128.
The output is full-range RGB, 255 E'R, 255 E'G and 255 E'B. So each channel is a * (Y - y0) + b * (U - 128) + c * (V - 128)
with a = 255 / 219 and the chroma terms scaled by 255 / 224 for a limited source, and a = 1 with the chroma terms
unscaled for a full one.

The integer table. Each coefficient is the real one times 1024, rounded to nearest. The constant is
-(cy * y0 + cu * 128 + cv * 128) + 512 in those integer coefficients: neutral chroma (128, 128) then contributes nothing,
and the 512 makes the converter's truncating shift round to nearest.

The tables are in the order of A733_G2D_CSC_* (include/a733_g2d_convert.h): BT.601 limited, BT.601 full, BT.709 limited,
BT.709 full. Each holds, for R, G and B in turn, the Y, U and V coefficients and the constant, as 32-bit words
sign-extended like the vendor's.

Usage: g2d-csc-tables.py [--check]
  without --check, writes include/a733_g2d_csc_tables.h; with it, exits 1 when that file differs from the generated one.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / 'include' / 'a733_g2d_csc_tables.h'
# (name, Kr, Kb, limited) in A733_G2D_CSC_* order.
TABLES = (('BT.601 limited', 0.299, 0.114, True), ('BT.601 full', 0.299, 0.114, False),
          ('BT.709 limited', 0.2126, 0.0722, True), ('BT.709 full', 0.2126, 0.0722, False))
COEFFICIENT_BITS, CONSTANT_BITS, FRACTION_BITS = 13, 20, 10


def real(kr, kb, limited):
    """The real matrix: per output channel R, G, B the (Y, U, V) coefficients, and the luma offset y0."""
    kg = 1 - kr - kb
    ys, cs = (255 / 219, 255 / 224) if limited else (1.0, 1.0)
    rows = ((ys, 0.0, cs * 2 * (1 - kr)),
            (ys, -cs * 2 * kb * (1 - kb) / kg, -cs * 2 * kr * (1 - kr) / kg),
            (ys, cs * 2 * (1 - kb), 0.0))
    return rows, (16 if limited else 0)


def integer(kr, kb, limited):
    """The 12 table values: per channel the three integer coefficients and the constant."""
    rows, y0 = real(kr, kb, limited)
    out = []
    for row in rows:
        cy, cu, cv = (int(round(x * (1 << FRACTION_BITS))) for x in row)
        out += [cy, cu, cv, -(cy * y0 + cu * 128 + cv * 128) + (1 << (FRACTION_BITS - 1))]
    return out


def fits(value, bits):
    return -(1 << (bits - 1)) <= value < (1 << (bits - 1))


def tables():
    """[(name, 12 values)] in A733_G2D_CSC_* order; SystemExit when a value does not fit its field."""
    out = []
    for name, kr, kb, limited in TABLES:
        values = integer(kr, kb, limited)
        for i, v in enumerate(values):
            if not fits(v, CONSTANT_BITS if i % 4 == 3 else COEFFICIENT_BITS):
                sys.exit(f'{name} value {i} ({v}) does not fit its field')
        out.append((name, values))
    return out


def header():
    lines = ['/* SPDX-License-Identifier: GPL-2.0-or-later */',
             '/* Generated by tools/g2d-csc-tables.py from the BT.601 and BT.709 matrices; edit the generator, not this',
             ' * file. The G2D mixer\'s YUV-to-RGB tables in A733_G2D_CSC_* order: for R, G and B the Y, U and V',
             ' * coefficients with 10 fraction bits and the constant, which includes 512 so that the converter\'s',
             ' * truncating shift rounds to nearest. */',
             '#ifndef SUNSTONE_A733_G2D_CSC_TABLES_H', '#define SUNSTONE_A733_G2D_CSC_TABLES_H', '#include <stdint.h>',
             'static const int32_t a733_g2d_csc_tables[4][12] = {']
    for name, values in tables():
        words = [f'{v}' if v >= 0 else f'(int32_t)0x{v & 0xffffffff:08x}' for v in values]
        lines.append(f'    /* {name}: R, G, B */')
        lines.append('    {' + ',\n     '.join(', '.join(words[4 * c:4 * c + 4]) for c in range(3)) + '},')
    lines += ['};', '#endif', '']
    return '\n'.join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    text = header()
    if a.check:
        if not HEADER.exists() or HEADER.read_text() != text:
            sys.exit(f'{HEADER.relative_to(ROOT)} is not the generator\'s output; run tools/g2d-csc-tables.py')
        print(f'{HEADER.relative_to(ROOT)} is current')
        return
    HEADER.write_text(text)
    print(f'wrote {HEADER.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
