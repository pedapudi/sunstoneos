#!/usr/bin/env python3
"""Write the header that sizes the OS NPU runtime's EL1 metadata arena exactly.

The arena (apps/os/npu.c, struct npu_meta) holds the tables the EL1 checks trust. Its size is a function of the image's
declaration and its graphs, so the build computes it with the same code that prepares the runtime: the sizing call
npu_runtime_meta_bytes_with, run on the host by checks/npu-pool-size.py with the image's catalogue and selection. The image links
exactly that many bytes and refuses at start if the session's declaration needs more.

  npu-meta-header.py --artifacts A --models L --slots N --output os-npu-meta.h [--bounds CAP,GRAPH,TENSOR] [--queue LINKS,IMAGE]
                     [--select ...]   (the catalogue tool's selection arguments)
"""
import argparse, json, os, subprocess, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument('--artifacts', type=Path, required=True)
ap.add_argument('--models', type=Path, required=True)
ap.add_argument('--slots', type=int, help='slots (default: one for each model, sized by its own graph)')
ap.add_argument('--uniform', action='store_true', help='every slot sized for the largest graph (an image without a queue)')
ap.add_argument('--bounds')
ap.add_argument('--queue')
ap.add_argument('--select', nargs=argparse.REMAINDER, help='last: the catalogue tool\'s selection arguments')
ap.add_argument('--output', type=Path, required=True)
ap.add_argument('--work', type=Path, required=True, help='a directory that receives the host build')
a = ap.parse_args()
a.work.mkdir(parents=True, exist_ok=True)
command = [sys.executable, str(ROOT / 'checks/npu-pool-size.py'), '--artifacts', str(a.artifacts), '--models', str(a.models),
           '--json', '--output', tempfile.mkdtemp(prefix='meta-', dir=a.work) + '/run']
if a.slots: command += ['--slots', str(a.slots)]
if a.uniform: command += ['--uniform']
for flag, value in (('--bounds', a.bounds), ('--queue', a.queue)):
    if value: command += [flag, value]
if a.select is not None: command += ['--select', *a.select]
done = subprocess.run(command, capture_output=True, text=True)
if done.returncode: sys.exit('the NPU sizing run failed: ' + (done.stdout + done.stderr)[-800:])
meta = json.loads(done.stdout.strip().splitlines()[-1])['meta_bytes']
assert meta > 0
text = ('/* Generated by tools/npu-meta-header.py: the EL1 metadata arena of the OS NPU runtime, sized exactly for the declaration. */\n'
        '#define OS_NPU_META_BYTES %dULL\n' % meta)
if not a.output.exists() or a.output.read_text() != text: a.output.write_text(text)
print(meta)
