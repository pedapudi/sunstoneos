#!/usr/bin/env python3
"""Link the reviewed NPU session catalogue into the board image.

Reads tools/npu-session-models.json for the catalogue order and each model's
SHA-256 and size, verifies the model file that the artifacts map names for each
entry, and writes C arrays, the npu_board_models table and
npu_board_catalogue_digest: SHA-256 over the model digests in catalogue order.
The artifacts map is the same JSON as checks/npu-session.py takes (name to
{"model": path, ...}); only the model files are read.
"""
import argparse,hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--artifacts',type=Path,required=True);p.add_argument('--output',type=Path,required=True)
    a=p.parse_args()
    catalogue=json.loads((ROOT/'tools/npu-session-models.json').read_text())['models']
    paths=json.loads(a.artifacts.read_text())
    text='/* Generated by apps/npu-board/catalogue.py from the reviewed catalogue. */\n#include "npu-board.h"\n'
    digests=b'';rows=[]
    for i,entry in enumerate(catalogue):
        data=Path(paths[entry['name']]['model']).read_bytes()
        digest=hashlib.sha256(data).digest()
        if len(data)!=entry['model']['bytes'] or digest.hex()!=entry['model']['sha256']:
            raise SystemExit(f"{entry['name']}: model does not match the catalogue")
        digests+=digest
        text+=f'static const unsigned char model_{i}[{len(data)}] __attribute__((aligned(64)))={{'+','.join(map(str,data))+'};\n'
        rows.append(f'{{model_{i},sizeof(model_{i})}}')
    if len(rows)!=5:raise SystemExit('The board image links the five catalogue models')
    text+='const struct npu_runtime_model npu_board_models[NPU_BOARD_MODELS]={'+','.join(rows)+'};\n'
    text+='const uint8_t npu_board_catalogue_digest[32]={'+','.join(map(str,hashlib.sha256(digests).digest()))+'};\n'
    a.output.write_text(text)
if __name__=='__main__':main()
