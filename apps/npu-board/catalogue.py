#!/usr/bin/env python3
"""Link the board application's NPU models into the board image.

Reads the application's model list (apps/npu-board/npu-models.json) for the
model order and tools/npu-session-models.json for each model's SHA-256 and
size, verifies the model file that the artifacts map names for each entry,
and writes C arrays, the npu_board_models table with npu_board_model_count
and npu_board_catalogue_digest: SHA-256 over the model digests in list order.
The artifacts map is the same JSON as checks/npu-session.py takes (name to
{"model": path, ...}); only the model files are read.
"""
import argparse,hashlib,importlib.util,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
MODELS=ROOT/'apps/npu-board/npu-models.json'
def catalogue_tool():
    spec=importlib.util.spec_from_file_location('npu_session_catalogue',ROOT/'tools/npu-session-catalogue.py')
    tool=importlib.util.module_from_spec(spec);spec.loader.exec_module(tool);return tool
def models():
    """The board application's catalogue entries, in load-index order."""
    return catalogue_tool().application_models([MODELS])
def generate(artifacts, output):
    tool=catalogue_tool()
    paths=json.loads(Path(artifacts).read_text())
    text='/* Generated by apps/npu-board/catalogue.py from the board model list. */\n#include "npu-board.h"\n'
    digests=b'';rows=[]
    for i,entry in enumerate(tool.application_models([MODELS])):
        data=Path(tool.artifact_files(paths,entry['name'])['model']).read_bytes()
        digest=hashlib.sha256(data).digest()
        if len(data)!=entry['model']['bytes'] or digest.hex()!=entry['model']['sha256']:
            raise SystemExit(f"{entry['name']}: model does not match the catalogue")
        digests+=digest
        text+=f'static const unsigned char model_{i}[{len(data)}] __attribute__((aligned(64)))={{'+','.join(map(str,data))+'};\n'
        rows.append(f'{{model_{i},sizeof(model_{i})}}')
    text+='const struct npu_runtime_model npu_board_models[]={'+','.join(rows)+'};\n'
    text+=f'const unsigned npu_board_model_count={len(rows)}u;\n'
    text+='const uint8_t npu_board_catalogue_digest[32]={'+','.join(map(str,hashlib.sha256(digests).digest()))+'};\n'
    Path(output).write_text(text)
def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--artifacts',type=Path,required=True);p.add_argument('--output',type=Path,required=True)
    a=p.parse_args()
    generate(a.artifacts,a.output)
if __name__=='__main__':main()
