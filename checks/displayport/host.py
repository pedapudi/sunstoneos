#!/usr/bin/env python3
"""Exercise DisplayPort host durability against an actual frozen native reply.

Only physical authority is substituted for a MODEL-NOT-PHYSICAL bundle.
Transport and persistence failures are modeled; no native execution, device,
queue, visible-output or physical qualification claim follows.
"""
import argparse,hashlib,importlib.util,json,struct
from pathlib import Path
from unittest.mock import patch
ROOT=Path(__file__).resolve().parents[2]
def module(name,path):
    spec=importlib.util.spec_from_file_location(name,path);value=importlib.util.module_from_spec(spec);spec.loader.exec_module(value);return value

def main():
    names=('success','pending','fault','identity','terminal-proof','pd-generation','short','oversize','raw-failure','copied-failure','journal-failure','deadline')
    p=argparse.ArgumentParser(description=__doc__)
    for name in ('bundle','reply','native_session','output'):p.add_argument('--'+name,type=Path,required=True)
    p.add_argument('--case',action='append',choices=names)
    a=p.parse_args();a.output.mkdir(parents=True,exist_ok=False)
    caller=module('displayport_host_check',ROOT/'tools/check-a733-displayport-supervised.py')
    prep,host=caller.preparation,caller.host
    model=json.loads((a.bundle/'admission.json').read_bytes())
    assert model['modeled'] is True and model['physical_authority'] is False
    try:caller.freeze_bundle(a.bundle)
    except ValueError as error:assert 'Modeled DisplayPort evidence' in str(error)
    else:raise AssertionError('Production accepted modeled authority')
    with patch.object(prep,'physical_authority',lambda value:None):prepared=caller.freeze_bundle(a.bundle)
    session=prepared['_frozen']['session.bin'];original=a.native_session.read_bytes();raw=a.reply.read_bytes()
    assert raw[72:104]==hashlib.sha256(original).digest() and raw[104:136]==original[48:80]==session[48:80]
    assert struct.unpack_from('<3Q',raw,32)==struct.unpack_from('<3Q',original,24)
    assert hashlib.sha256(original).hexdigest()==prepared['_allocation']['source_session']
    assert host.decode(raw,original,allocation=prepared['_allocation'])['status']==1
    # Typed facts and epochs are intentionally regenerated by preparation.
    # Preserve all native terminal proofs while binding this exact modeled bundle.
    rebound=bytearray(raw);rebound[32:56]=session[24:48];rebound[72:104]=hashlib.sha256(session).digest()
    struct.pack_into('<Q',rebound,56,struct.unpack_from('<Q',session,32)[0])
    assert host.decode(bytes(rebound),session,allocation=prepared['_allocation'])['status']==1
    results=[]
    for name in a.case or names:
        out=a.output/name;out.mkdir();record={};clock=[1];writes=[];reads=[];count=[0];failed=[False]
        reply=bytearray(rebound)
        if name=='fault':struct.pack_into('<II',reply,16,2,1)
        if name=='identity':reply[72]^=1
        if name=='terminal-proof':struct.pack_into('<I',reply,208,2)
        if name=='pd-generation':struct.pack_into('<Q',reply,56,0)
        if name=='short':reply=reply[:-1]
        if name=='oversize':reply+=b'!'
        class Device:
            def write(self,endpoint,data,timeout):
                assert endpoint==2 and data==b'\0' and timeout>0;writes.append(bytes(data));return len(data)
            def read(self,endpoint,capacity,timeout):
                assert endpoint==0x81 and capacity==1025 and timeout>0;reads.append(capacity);count[0]+=1
                if name=='deadline':clock[0]=100
                if name=='pending' and count[0]==1:
                    pending=bytearray(rebound);struct.pack_into('<4I',pending,16,0,0,0,1)
                    pending[56:72]=bytes(16);pending[136:]=bytes(1024-136);return bytes(pending)
                return bytes(reply)
        original_durable=host.supervisor.durable_frame
        def durable(path,data):
            if not failed[0] and ((name=='raw-failure' and path.suffix=='.bin') or
                    (name=='copied-failure' and path.name=='copied-observation.json')):
                failed[0]=True;raise OSError('Modeled evidence persistence failure')
            return original_durable(path,data)
        def save():
            if name=='journal-failure' and record.get('displayport_result')=='observed-success' and not failed[0]:
                failed[0]=True;raise OSError('Modeled final journal failure')
            caller.supervisor.save_json(out/'session.json',record)
        failures=('identity','terminal-proof','pd-generation','short','oversize','raw-failure','copied-failure','journal-failure','deadline')
        with patch.object(host.supervisor,'durable_frame',durable):
            try:host.capture_device(Device(),lambda:None,100,session,out,record,save,allocation=prepared['_allocation'],now=lambda:clock[0],pause=lambda _:None)
            except (OSError,ValueError,TimeoutError):assert name in failures and record['displayport_result']=='unobserved'
            else:assert name not in failures and record['displayport_result']==('observed-failure' if name=='fault' else 'observed-success')
        assert len(writes)==len(reads)==(2 if name=='pending' else 1) and all(packet==b'\0' for packet in writes)
        assert record['physical_qualified'] is False
        results.append(dict(case=name,queries=len(writes),result=record['displayport_result']))
    result=dict(passed=True,physical_access=False,physical_authority=False,scope=__doc__,cases=results,
        image_sha256=prepared['image_sha256'],reply_sha256=hashlib.sha256(raw).hexdigest(),
        native_session_sha256=hashlib.sha256(original).hexdigest(),production_refused=True)
    (a.output/'result.json').write_text(json.dumps(result,indent=2)+'\n');print(json.dumps(result))
if __name__=='__main__':main()
